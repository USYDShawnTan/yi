"""Rebuild self-hosted webfonts: fonttools==4.61.1 and brotli==1.2.0.

Run manually after changing the preferred character subset; Vercel uses the
committed outputs. The extension subset covers the remaining source characters.
"""

from hashlib import sha256
from functools import partial
from pathlib import Path
import json
import tempfile
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.ttLib import woff2

# FontTools 4.61.1 uses Brotli's expensive quality-11 default and does not
# expose a compression-level option. Quality 6 preserves the same font data
# while keeping a complete CJK font rebuild practical. This override affects
# only this offline generator process; decoding/coverage are checked below.
woff2.brotli.compress = partial(woff2.brotli.compress, quality=6)

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "public/fonts"
CACHE = Path(tempfile.gettempdir()) / "yixue-wenkai"
VERSION = "v1.530"
BASE = f"https://github.com/lxgw/LxgwWenKai/releases/download/{VERSION}"
FILES = {
    "LXGWWenKai-Regular.ttf": "2d73eea94ad808999d90c0000c239a84a33b09d4bc6ab6c5b8bbf1eda8a7fc8b",
    "LXGWWenKai-Medium.ttf": "f4b8a34d1f838fe411540cb7c97b1c384ac9738a876c4104500bc42508b2312a",
    "OFL.txt": "1a25e35da1031c6c3436fde545bb9cb5aca954e9873afe510c834b8b79bd21a0",
}


def source(name):
    path = CACHE / name
    if not path.exists():
        url = f"{BASE}/{name}" if name != "OFL.txt" else f"https://raw.githubusercontent.com/lxgw/LxgwWenKai/{VERSION}/OFL.txt"
        with urllib.request.urlopen(url, timeout=120) as response:
            path.write_bytes(response.read())
    assert sha256(path.read_bytes()).hexdigest() == FILES[name], f"Checksum mismatch: {name}"
    return path


def ranges(points):
    result = []
    start = previous = None
    for point in sorted(points):
        if previous is not None and point != previous + 1:
            result.append(f"U+{start:X}" if start == previous else f"U+{start:X}-{previous:X}")
            start = point
        if start is None:
            start = point
        previous = point
    if start is not None:
        result.append(f"U+{start:X}" if start == previous else f"U+{start:X}-{previous:X}")
    return ",".join(result)


OUTPUT.mkdir(parents=True, exist_ok=True)
CACHE.mkdir(parents=True, exist_ok=True)
corpus = "".join(p.read_text() for p in sorted((ROOT / "src").glob("*.tsx")))
corpus += (ROOT / "src/content.ts").read_text()
corpus += (ROOT / "data/hexagrams.json").read_text()
# Include ASCII, Latin pinyin, and common punctuation independently of content.
preferred = {ord(char) for char in corpus} | set(range(0x20, 0x300)) | set(range(0x2000, 0x2070))
css = ["/* Generated by scripts/prepare-fonts.py. Source: LXGW WenKai v1.530, OFL-1.1. */"]
manifest = {"upstream": "https://github.com/lxgw/LxgwWenKai", "version": VERSION,
            "license": "OFL-1.1", "family": "Yixue WenKai", "files": []}
for style, weight in [("Regular", 400), ("Medium", 500)]:
    filename = f"LXGWWenKai-{style}.ttf"
    original = source(filename)
    with TTFont(original) as font:
        supported = set(font.getBestCmap())
    primary = preferred & supported
    extension = supported - primary
    assert not primary & extension and primary | extension == supported
    for label, characters in [("core", primary), ("extension", extension)]:
        font = TTFont(original, recalcTimestamp=False)
        options = subset.Options()
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.name_legacy = True
        processor = subset.Subsetter(options=options)
        processor.populate(unicodes=characters)
        processor.subset(font)
        # Use a distinct internal name for redistributed web subsets (OFL RFNs).
        names = {1: "Yixue WenKai", 2: style, 3: f"YixueWenKai-{style}-{VERSION}",
                 4: f"Yixue WenKai {style}", 6: f"YixueWenKai-{style}",
                 16: "Yixue WenKai", 17: style}
        for record in list(font["name"].names):
            if record.nameID in names:
                font["name"].setName(names[record.nameID], record.nameID,
                                     record.platformID, record.platEncID, record.langID)
        font.flavor = "woff2"
        target = OUTPUT / f"yixue-wenkai-{style.lower()}-{label}.woff2"
        font.save(target)
        font.close()
        with TTFont(target) as exported:
            assert set(exported.getBestCmap()) == characters
        css.append(f'@font-face {{\n  font-family: "Yixue WenKai";\n  font-style: normal;\n  font-weight: {weight};\n  font-display: swap;\n  src: url("/fonts/{target.name}") format("woff2");\n  unicode-range: {ranges(characters)};\n}}')
        manifest["files"].append({"file": target.name, "weight": weight,
                                  "characters": len(characters), "bytes": target.stat().st_size,
                                  "sha256": sha256(target.read_bytes()).hexdigest(),
                                  "source": f"{BASE}/{filename}", "sourceSha256": FILES[filename]})
        print(target.name, len(characters), "characters", target.stat().st_size, "bytes", flush=True)
(OUTPUT / "OFL.txt").write_bytes(source("OFL.txt").read_bytes())
(OUTPUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
(ROOT / "src/fonts.css").write_text("\n\n".join(css) + "\n")
