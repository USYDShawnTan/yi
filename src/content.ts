export const imageOf = (name: TrigramName) =>
  trigrams.find((t) => t.name === name)!.image;
export const numberLabel = (id: number) => String(id).padStart(2, "0");
export function filterHexagrams(search: string, upper: string, lower: string) {
  const q = search.trim();
  return hexagrams.filter(
    (h) =>
      (!q ||
        (/^\d+$/.test(q)
          ? h.id === Number(q)
          : [h.name, h.traditional, h.id === 33 ? "遯" : ""].some((n) =>
              n.includes(q),
            ))) &&
      (!upper || h.upper === upper) &&
      (!lower || h.lower === lower),
  );
}
